// ============================================================================
// T2Editor AI Tool 만들기 — 5분 가이드
// ============================================================================
//
// T2Editor AI는 "T2Editor를 조작할 수 있는 모든 것"을 뜻합니다. 콘텐츠를
// 쓰고 고치는 능력은 t2llm.js(T2LLM)가 담당하고, 무언가를 찾아오는(검색·조회)
// 능력은 이 폴더의 t2ai_tool_*.js 파일들이 각각 담당합니다.
//
// 새 Tool 파일 하나 = 새 능력 하나. 지우면 그 능력만 사라집니다.
//
// ── 최소 템플릿 ─────────────────────────────────────────────────────────────
//
//   // Path: T2Editor/extend/js/t2ai_tool_my_thing.js
//   (function () {
//       'use strict';
//       if (!window.T2AITools) {
//           console.warn('[T2AI] t2ai_core.js 미로드 — 등록 건너뜀');
//           return;
//       }
//
//       T2AITools.register({
//           name: 'my_thing',                 // 소문자/숫자/언더스코어만
//           description: '이 Tool이 하는 일을 한 문장으로.',
//           params: {                         // LLM에게 보여줄 인자 설명 (자유 텍스트)
//               foo: '무엇을 넣어야 하는지 설명',
//           },
//           source: 't2ai_tool_my_thing.js',  // 선택, 디버깅용
//
//           // ── (선택) 유저 대상 UI 노출 ─────────────────────────────────────
//           // ai_complex 같은 "Tool on/off" 화면에 이 Tool을 보이게 하려면
//           // ui를 선언한다. 선언하지 않으면 내부/보조 Tool로 간주되어 유저
//           // 화면에는 안 나타나지만 run()은 여전히 가능하다.
//           ui: {
//               label: '유저에게 보일 짧은 이름',       // 예: '이미지 검색'
//               icon: 'material-icons 아이콘 이름',     // 예: 'image'
//               description: '유저 눈높이로 lite한 1~2문장 설명',
//               usage: '언제/어떻게 쓰이는지 lite한 예시 1~2문장',
//           },
//           // group을 지정하면 같은 group의 다른 Tool들과 UI에서 한 항목으로
//           // 묶이고 on/off도 함께 적용된다(예: memory_remember/recall/forget을
//           // 모두 group:'memory'로 묶어 "장기 기억" 하나로 보여주기). 생략 시
//           // 자기 name이 곧 group(단독 항목).
//           group: 'my_thing',
//
//           async run(args, ctx) {
//               // 실제 동작. 무엇을 반환하든 자유(객체 권장).
//               // 실패해도 여기서 그냥 throw 하면 됨 — T2AIHarness.run() 이
//               // 알아서 { ok:false, error } 로 감싸줌.
//               return { hello: args.foo };
//           },
//       });
//   })();
//
// ── 규칙 ────────────────────────────────────────────────────────────────────
// 1. 파일명은 t2ai_tool_ 로 시작하는 게 관례(필수는 아니지만 정렬·식별에 도움).
// 2. 다른 t2ai_tool_*.js 파일을 절대 import/참조하지 않는다 — Tool끼리는
//    서로 몰라야 한다. 이래야 파일 하나를 지워도 다른 Tool이 안 죽는다.
// 3. window.T2AITools / window.T2AIHarness (코어)에만 의존한다.
// 4. 외부 서비스(dsclub 등)를 쓰는 Tool은 실패를 조용히 삼키지 말고
//    { ok:false, message } 형태로 명확히 알린다 — LLM이 "이 Tool은 지금
//    안 되는구나"를 바로 알아채고 다른 방법을 찾을 수 있게.
// 5. register()는 같은 name으로 다시 불러도 에러 없이 덮어쓴다 — 개발 중
//    파일을 고쳐서 페이지만 새로고침하면 최신 코드가 바로 반영된다.
// 6. 유저 대상 이름/설명/사용법 문구(label, description, usage)는 반드시
//    ui 필드 안에만 적는다. ai_complex.js 같은 소비자 쪽 파일에 이런 문구를
//    직접 하드코딩하지 않는다 — Tool 파일이 유일한 출처(source of truth)다.
//
// ── 삭제하기 ─────────────────────────────────────────────────────────────────
// t2ai_tool_*.js 파일 하나를 서버에서 지우면 끝. 다음 페이지 로드부터
// 그 Tool은 T2AIHarness.spec() 목록에서 자동으로 사라진다. 재부팅도,
// 다른 파일 수정도 필요 없다.
//
// (선택) 런타임에 즉시 끄고 싶다면 파일을 지우지 않고도:
//   T2AITools.unregister('my_thing');
// 콘솔에서 바로 실행 가능.
//
// ── 코어(t2ai_core.js) 자체를 고치고 싶다면 ──────────────────────────────────
// 레지스트리 동작(register/unregister/run/spec)만 다루는 아주 작은 파일입니다.
// 이 하네스가 필요 없다면(예: T2Editor AI 기능 자체를 완전히 뺀다면)
// t2ai_core.js 와 t2ai_tool_*.js 전부를 통째로 지우면 됩니다 —
// editor.lib.php, 플러그인 등 다른 어떤 코드도 이 파일들 존재를 전제하지
// 않으므로 아무것도 깨지지 않습니다.
